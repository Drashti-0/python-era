a = {1, 2, 3, 4, 5}
b = {4, 5, 6, 7, 8}

#union
c=a.union(b)
print("Union of A and B:", c)

#intersection
d=a.intersection(b)
print("Intersection A and B:", d)

#Difference
#only that element je a ma chhe and b ma nthi 
e=a.difference(b)
print("Difference is : ",e)

#symmetric difference
f=a.symmetric_difference(b)
print("Symmetric difference is: ", f)




